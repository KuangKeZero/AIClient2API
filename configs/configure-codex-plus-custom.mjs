import fs from 'fs';
import crypto from 'crypto';
const configPath = '/app/configs/config.json';
const poolsPath = '/app/configs/provider_pools.json';
const modelsPath = '/app/configs/custom_models.json';
const ts = new Date().toISOString().replace(/[^0-9]/g, '').slice(0, 14);
const key = 'sk-57e30a8bd51e227dad853772188cfe5f73fe8b7ff7e63de63ce121c8f72bb509';
const baseUrl = 'https://codex.subgo.qzz.io/v1';
const customProvider = 'openaiResponses-custom-plus';
const plusProvider = 'openai-codex-oauth-plus';
const listProvider = 'openai-codex-oauth';
const backup = (p) => { const b = `${p}.bak-codex-plus-custom-${ts}`; fs.copyFileSync(p, b); return b; };
const configBackup = backup(configPath);
const poolsBackup = backup(poolsPath);
const modelsBackup = backup(modelsPath);
const config = JSON.parse(fs.readFileSync(configPath, 'utf8'));
const pools = JSON.parse(fs.readFileSync(poolsPath, 'utf8'));
const models = JSON.parse(fs.readFileSync(modelsPath, 'utf8'));
if (!Array.isArray(pools[customProvider])) pools[customProvider] = [];
const arr = pools[customProvider];
let item = arr.find(x => String(x.customName || '').toLowerCase() === 'codex-subgo-plus' || x.OPENAI_BASE_URL === baseUrl || x.OPENAI_API_BASE_URL === baseUrl);
if (!item) { item = {}; arr.push(item); }
item.uuid = item.uuid || crypto.randomUUID();
item.customName = 'codex-subgo-plus';
item.OPENAI_BASE_URL = baseUrl;
delete item.OPENAI_API_BASE_URL;
item.OPENAI_API_KEY = key;
item.supportedModels = ['gpt-5.5'];
item.isDisabled = false;
item.isHealthy = true;
item.errorCount = 0;
delete item.lastErrorMessage;
delete item.needsRefresh;
if (!Array.isArray(pools[plusProvider])) pools[plusProvider] = [];
config.providerFallbackChain = config.providerFallbackChain && typeof config.providerFallbackChain === 'object' ? config.providerFallbackChain : {};
const chain = Array.isArray(config.providerFallbackChain[plusProvider]) ? config.providerFallbackChain[plusProvider] : [];
config.providerFallbackChain[plusProvider] = [...new Set([...chain, customProvider])];
function upsertModel(id, name, actualProvider, description) { let m = models.find(x => x.id === id || x.alias === id); if (!m) { m = {}; models.push(m); } m.id = id; m.name = name; m.provider = listProvider; m.actualProvider = actualProvider; m.actualModel = 'gpt-5.5'; m.description = description; delete m.alias; return m; }
upsertModel('gpt-5.5-free', 'GPT-5.5 Free', 'openai-codex-oauth', 'Route to the free Codex OAuth pool');
upsertModel('gpt-5.5-plus', 'GPT-5.5 Plus', customProvider, 'Route to the OpenAI Responses Plus provider');
upsertModel('gpt-5.5-pro', 'GPT-5.5 Pro', 'openai-custom', 'Route to the OpenAI Custom provider');
fs.writeFileSync(configPath, JSON.stringify(config, null, 2) + '\n');
fs.writeFileSync(poolsPath, JSON.stringify(pools, null, 2) + '\n');
fs.writeFileSync(modelsPath, JSON.stringify(models, null, 2) + '\n');
console.log(JSON.stringify({backups:{configBackup,poolsBackup,modelsBackup}, added:{provider:customProvider, customName:item.customName, uuid:item.uuid, baseUrl:item.OPENAI_BASE_URL, keyHash:crypto.createHash('sha256').update(key).digest('hex').slice(0,16)}, fallback:{[plusProvider]:config.providerFallbackChain[plusProvider]}, customModels:models.filter(m => ['gpt-5.5-free','gpt-5.5-plus','gpt-5.5-pro'].includes(m.id))}, null, 2));
